export const MAIL_UI: Record<'pt' | 'en' | 'es', MailUi> = { pt, en, es };

export function mailUi(explicit?: string | null): MailUi {
  return MAIL_UI[baseUiLang(preferredUiLang(explicit))] ?? pt;
}

export function mailError(ui: MailUi, code: string | null | undefined): string {
  return (code && ui.errors[code]) || ui.errors.generic;
}
